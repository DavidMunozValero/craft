#!/usr/bin/env python
"""Run the GA (direct encoding) timetabling optimization.

Loads the synthetic instance generated by notebook 0.0 (``timetable.yaml`` +
``revenue.yaml``), solves the revenue-maximization problem with the direct
genetic encoding, and saves the convergence history, the best schedule and
evolution filmstrips (genome and timetable) under ``--output-dir``.

Examples:
    python scripts/run_ga.py --seed 42 --pop-size 40 --epoch 100
    python scripts/run_ga.py --pop-size 60 --epoch 200 --no-plots
"""

import argparse
from pathlib import Path

import numpy as np

from craft.ga import GA, GATimetabling, load_problem


def save_filmstrips(
    problem: GATimetabling, ga: GA, seed: int, output_dir: Path
) -> tuple:
    """Save genome and timetable evolution filmstrips for the run."""
    from craft.ga.plotting import plot_genome_filmstrip, plot_timetable_filmstrip

    steps = np.linspace(0, len(ga.convergence) - 1, 4).astype(int)
    titles = [f"generación {step}" for step in steps]
    genomes = ga.best_genomes[steps]

    genome_fig = plot_genome_filmstrip(problem, genomes, titles)
    genome_path = output_dir / f"genome_evolution_ga_seed{seed}.png"
    genome_fig.savefig(genome_path, dpi=150, bbox_inches="tight")

    timetable_fig = plot_timetable_filmstrip(problem, genomes, titles)
    timetable_path = output_dir / f"timetable_evolution_ga_seed{seed}.png"
    timetable_fig.savefig(timetable_path, dpi=150, bbox_inches="tight")
    return genome_path, timetable_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run GA timetabling optimization (direct encoding)."
    )
    parser.add_argument(
        "--timetable",
        type=Path,
        default=Path("data/synthetic/timetable.yaml"),
        help="Timetable YAML from notebook 0.0",
    )
    parser.add_argument(
        "--revenue",
        type=Path,
        default=Path("data/synthetic/revenue.yaml"),
        help="Revenue behavior YAML from notebook 0.0",
    )
    parser.add_argument(
        "--seed", type=int, default=42, help="Random seed (default: 42)"
    )
    parser.add_argument(
        "--pop-size", type=int, default=40, help="GA population size (default: 40)"
    )
    parser.add_argument(
        "--epoch", type=int, default=100, help="Number of generations (default: 100)"
    )
    parser.add_argument(
        "--pc", type=float, default=0.9, help="Crossover probability (default: 0.9)"
    )
    parser.add_argument(
        "--pm",
        type=float,
        default=0.05,
        help="Per-gene mutation probability (default: 0.05)",
    )
    parser.add_argument(
        "--lambda",
        dest="conflict_penalty",
        type=float,
        default=2.0,
        help="Conflict penalty weight lambda (default: 2.0)",
    )
    parser.add_argument(
        "--max-stop-time",
        type=int,
        default=10,
        help="Maximum dwell-time extension in minutes (default: 10)",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("data/results"),
        help="Directory for the run artifacts (default: data/results)",
    )
    parser.add_argument("--no-plots", action="store_true", help="Skip filmstrip export")
    parser.add_argument("--quiet", action="store_true", help="Suppress progress output")
    args = parser.parse_args()

    output_dir = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    problem = load_problem(
        args.timetable,
        args.revenue,
        max_stop_time=args.max_stop_time,
        conflict_penalty=args.conflict_penalty,
    )
    ga = GA(problem, pop_size=args.pop_size, pc=args.pc, pm=args.pm)
    history = ga.optimize(epoch=args.epoch, seed=args.seed, verbose=not args.quiet)

    convergence_path = output_dir / f"convergence_ga_seed{args.seed}.csv"
    history.to_csv(convergence_path, index=False)

    schedule_df = problem.schedule_frame(ga.best_solution)
    schedule_path = output_dir / f"best_schedule_ga_seed{args.seed}.csv"
    schedule_df.to_csv(schedule_path, index=False)

    conflicts = len(problem.conflicting_pairs(ga.best_genome))
    print(
        f"\nGA results: fitness={ga.best_fitness:.2f}, "
        f"planned={len(schedule_df)}/{problem.n_services}, conflicts={conflicts}"
    )
    print(
        f"Greedy baseline at requested times: "
        f"revenue={problem.greedy_baseline()[1]:.2f}"
    )
    print(f"Convergence   -> {convergence_path}")
    print(f"Best schedule -> {schedule_path}")

    if not args.no_plots:
        genome_path, timetable_path = save_filmstrips(
            problem, ga, args.seed, output_dir
        )
        print(f"Filmstrips    -> {genome_path}, {timetable_path}")


if __name__ == "__main__":
    main()
