#!/usr/bin/env python
"""Run the NSGA-II (direct encoding) revenue-fairness optimization.

Loads the synthetic instance generated by notebook 0.0 (``timetable.yaml`` +
``revenue.yaml``) and solves the bi-objective problem (penalized revenue +
capacity-aware fairness over the RU allocation) with NSGA-II. Artifacts under
``--output-dir``: convergence history, Pareto front table, knee-point
schedule, hypervolume evolution (CSV + figure) and the Pareto scatter.

Examples:
    python scripts/run_nsga2.py --seed 42 --pop-size 40 --epoch 100
    python scripts/run_nsga2.py --fair-index gini --alpha 10 --no-plots
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from craft.ga import NSGA2, GATimetabling, load_problem, revenue_fairness_objectives
from craft.ga.nsga2 import hypervolume, knee_index
from craft.ga.objectives import FAIRNESS_ALPHA

HYPERVOLUME_REFERENCE = (0.0, 0.0)


def build_front_frame(problem: GATimetabling, solver: NSGA2) -> pd.DataFrame:
    """Pareto front table with per-point diagnostics.

    Args:
        problem: The solved timetabling problem.
        solver: The finished NSGA-II run.

    Returns:
        One row per front member (sorted by descending revenue) with its
        objectives, planned services and residual conflicts.
    """
    rows = []
    for genome, revenue, fairness in zip(
        solver.pareto_genomes, solver.pareto_values[:, 0], solver.pareto_values[:, 1]
    ):
        rows.append(
            {
                "revenue": revenue,
                "fairness": fairness,
                "planned": int(problem.decode(genome).discrete.sum()),
                "conflicts": len(problem.conflicting_pairs(genome)),
            }
        )
    return pd.DataFrame(rows)


def save_plots(
    front: np.ndarray,
    knee: int,
    hypervolumes: np.ndarray,
    seed: int,
    index: str,
    alpha: float,
    output_dir: Path,
) -> tuple:
    """Save the Pareto scatter and the hypervolume evolution figures."""
    import matplotlib.pyplot as plt

    scatter_path = output_dir / f"pareto_scatter_nsga2_seed{seed}.png"
    fig, ax = plt.subplots(figsize=(7, 5))
    ax.scatter(front[:, 0], front[:, 1], s=45, label="frente de Pareto")
    ax.scatter(
        front[knee, 0],
        front[knee, 1],
        marker="*",
        s=260,
        color="crimson",
        zorder=3,
        label="knee",
    )
    ax.set_xlabel("Ingreso penalizado")
    ax.set_ylabel(f"Equidad ({index}, alpha={alpha:g})")
    ax.set_title(f"NSGA-II seed {seed}")
    ax.grid(alpha=0.3)
    ax.legend()
    fig.savefig(scatter_path, dpi=150, bbox_inches="tight")
    plt.close(fig)

    hypervolume_path = output_dir / f"hypervolume_nsga2_seed{seed}.png"
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(hypervolumes, color="tab:blue")
    ax.set_xlabel("Generación")
    ax.set_ylabel(
        f"Hipervolumen (ref={HYPERVOLUME_REFERENCE[0]:g}, {HYPERVOLUME_REFERENCE[1]:g})"
    )
    ax.set_title(f"NSGA-II seed {seed}")
    ax.grid(alpha=0.3)
    fig.savefig(hypervolume_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    return scatter_path, hypervolume_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Run bi-objective (revenue + fairness) NSGA-II timetabling "
            "optimization (direct encoding)."
        )
    )
    parser.add_argument(
        "--timetable",
        type=Path,
        default=Path("data/synthetic/timetable.yaml"),
        help="Timetable YAML from notebook 0.0",
    )
    parser.add_argument(
        "--revenue",
        type=Path,
        default=Path("data/synthetic/revenue.yaml"),
        help="Revenue behavior YAML from notebook 0.0",
    )
    parser.add_argument(
        "--seed", type=int, default=42, help="Random seed (default: 42)"
    )
    parser.add_argument(
        "--pop-size",
        type=int,
        default=40,
        help="NSGA-II population size (default: 40)",
    )
    parser.add_argument(
        "--epoch", type=int, default=100, help="Number of generations (default: 100)"
    )
    parser.add_argument(
        "--pc", type=float, default=0.9, help="Crossover probability (default: 0.9)"
    )
    parser.add_argument(
        "--pm",
        type=float,
        default=0.05,
        help="Per-gene mutation probability (default: 0.05)",
    )
    parser.add_argument(
        "--lambda",
        dest="conflict_penalty",
        type=float,
        default=2.0,
        help="Conflict penalty weight lambda (default: 2.0)",
    )
    parser.add_argument(
        "--max-stop-time",
        type=int,
        default=10,
        help="Maximum dwell-time extension in minutes (default: 10)",
    )
    parser.add_argument(
        "--fair-index",
        choices=["jain", "gini", "atkinson"],
        default="jain",
        help="Fairness index of the second objective (default: jain)",
    )
    parser.add_argument(
        "--alpha",
        type=float,
        default=None,
        help=(
            "Sensitivity exponent of the fairness index "
            "(default: calibrated per index: 25 for jain/atkinson, 10 for gini)"
        ),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("data/results"),
        help="Directory for the run artifacts (default: data/results)",
    )
    parser.add_argument("--no-plots", action="store_true", help="Skip figures")
    parser.add_argument("--quiet", action="store_true", help="Suppress progress output")
    args = parser.parse_args()

    output_dir = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    alpha = args.alpha if args.alpha is not None else FAIRNESS_ALPHA[args.fair_index]
    problem = load_problem(
        args.timetable,
        args.revenue,
        max_stop_time=args.max_stop_time,
        conflict_penalty=args.conflict_penalty,
    )
    objectives = revenue_fairness_objectives(
        problem, index=args.fair_index, alpha=alpha
    )
    solver = NSGA2(
        problem,
        pop_size=args.pop_size,
        pc=args.pc,
        pm=args.pm,
        objectives=objectives,
    )
    history = solver.optimize(epoch=args.epoch, seed=args.seed, verbose=not args.quiet)

    convergence_path = output_dir / f"convergence_nsga2_seed{args.seed}.csv"
    history.to_csv(convergence_path, index=False)

    front = solver.pareto_values
    front_df = build_front_frame(problem, solver)
    front_path = output_dir / f"pareto_front_nsga2_seed{args.seed}.csv"
    front_df.to_csv(front_path, index=False)

    knee = knee_index(front)
    knee_solution = problem.decode(solver.pareto_genomes[knee])
    schedule_df = problem.schedule_frame(knee_solution)
    schedule_path = output_dir / f"best_schedule_nsga2_seed{args.seed}.csv"
    schedule_df.to_csv(schedule_path, index=False)

    hypervolumes = np.array(
        [
            hypervolume(generation, HYPERVOLUME_REFERENCE)
            for generation in solver.pareto_history
        ]
    )
    hypervolume_df = pd.DataFrame(
        {
            "Iteration": np.arange(len(hypervolumes)),
            "Hypervolume": hypervolumes,
            "FrontSize": [len(generation) for generation in solver.pareto_history],
        }
    )
    hypervolume_path = output_dir / f"hypervolume_nsga2_seed{args.seed}.csv"
    hypervolume_df.to_csv(hypervolume_path, index=False)

    print(
        f"\nNSGA-II results: front={len(front)} points, "
        f"best revenue={solver.best_fitness:.2f}"
    )
    print(
        f"Knee point: revenue={front[knee, 0]:.2f}, "
        f"fairness={front[knee, 1]:.4f}, "
        f"planned={len(schedule_df)}/{problem.n_services}, "
        f"conflicts={front_df['conflicts'].iloc[knee]}"
    )
    print(f"Final hypervolume: {hypervolumes[-1]:.2f}")
    print(
        f"Greedy baseline at requested times: "
        f"revenue={problem.greedy_baseline()[1]:.2f}"
    )
    print(f"Convergence   -> {convergence_path}")
    print(f"Pareto front  -> {front_path}")
    print(f"Knee schedule -> {schedule_path}")
    print(f"Hypervolume   -> {hypervolume_path}")

    if not args.no_plots:
        scatter_path, figure_path = save_plots(
            front,
            knee,
            hypervolumes,
            args.seed,
            args.fair_index,
            alpha,
            output_dir,
        )
        print(f"Figures       -> {scatter_path}, {figure_path}")


if __name__ == "__main__":
    main()
