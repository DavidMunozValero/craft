"""Direct genetic encoding of the IM revenue-maximization timetabling problem.

A genome holds one block per service, ``[b, d1, ..., d_{n-1}]``, where ``b``
decides whether the service is scheduled and ``d`` are integer minute deltas
with respect to the departure times requested by the RU. Deltas accumulate
downstream when decoded, so the IM modification margin, the operating times
and the dwell caps hold by construction; inter-service conflicts are the only
remaining constraint and are handled as a fitness penalty.

The full design is described in ``docs/plan_ga_direct_encoding.md``.
"""

from collections import defaultdict
from copy import deepcopy
from pathlib import Path
from typing import Dict, Iterator, List, Mapping, Optional, Sequence, Tuple, Union

import numpy as np
import pandas as pd
import yaml
from geopy.distance import geodesic
from robin.supply.entities import Station, Supply

from ..common import Solution
from ..revenue import RevenueCalculator
from ..scheduling import ScheduleManager, cumulative_shifts, get_schedule_from_supply

Genome = Union[np.ndarray, Sequence[int]]


def load_problem(
    timetable_path: Union[str, Path],
    revenue_path: Union[str, Path],
    max_stop_time: int = 10,
    conflict_penalty: float = 2.0,
) -> "GATimetabling":
    """Build the problem from the files generated by notebook 0.0.

    The safety headway and the IM margin are read from the file metadata
    when present, falling back to the class defaults.

    Args:
        timetable_path: Path to the robin-format timetable YAML.
        revenue_path: Path to the revenue behavior YAML.
        max_stop_time: Maximum dwell-time extension, in minutes.
        conflict_penalty: Weight ``lambda`` of the conflict penalty.

    Returns:
        The ready-to-solve timetabling problem.
    """
    supply = Supply.from_yaml(path=str(timetable_path))
    with open(revenue_path) as handle:
        revenue_payload = yaml.safe_load(handle)
    with open(timetable_path) as handle:
        timetable = yaml.safe_load(handle)
    return GATimetabling(
        supply=supply,
        revenue_behavior=revenue_payload["services"],
        safe_headway=timetable.get("metadata", {}).get("safe_headway", 10),
        im_mod_margin=revenue_payload.get("metadata", {})
        .get("parameters", {})
        .get("im_mod_margin", 60),
        max_stop_time=max_stop_time,
        conflict_penalty=conflict_penalty,
    )


class CorridorConflicts:
    """Pairwise temporal conflicts between services sharing an ordered corridor.

    Reproduces the semantics of ``robin``'s ``ServiceScheduler``: for every
    corridor edge, two services that traverse it in the same direction
    conflict when their time gaps at the edge endpoints have opposite signs or
    are within twice the safety headway. Times at pass-through stations are
    interpolated linearly with distance.
    """

    def __init__(
        self,
        corridor: Sequence[Station],
        routes: Mapping[str, Sequence[Station]],
        row_of: Mapping[str, int],
        safe_headway: int,
    ) -> None:
        """Build the conflict model of one corridor.

        Args:
            corridor: Stations of the corridor in order.
            routes: Stops of each service, in travel order.
            row_of: Global matrix row of each service.
            safe_headway: Safety headway in minutes.
        """
        self.row_of = dict(row_of)
        self.headway = safe_headway
        self.position = {station.id: i for i, station in enumerate(corridor)}
        self.corridor_ids = [station.id for station in corridor]
        self.km: Dict[str, float] = {}
        accumulated = 0.0
        previous: Optional[Tuple[float, float]] = None
        for station in corridor:
            if previous is not None:
                accumulated += geodesic(previous, station.coordinates).km
            self.km[station.id] = accumulated
            previous = station.coordinates
        self._route_ids = {sid: [s.id for s in route] for sid, route in routes.items()}
        self._slots = {sid: self._slots_for(route) for sid, route in routes.items()}

    def _slots_for(
        self, route: Sequence[Station]
    ) -> List[Tuple[int, bool, int, float, float]]:
        """Precompute, per traversed corridor edge, the bracketing leg of the
        service and the interpolation fractions of both edge endpoints."""
        positions = [self.position[station.id] for station in route]
        kms = [self.km[station.id] for station in route]
        forward = positions[0] < positions[-1]
        slots = []
        for edge in range(min(positions), max(positions)):
            low = self.km[self.corridor_ids[edge]]
            high = self.km[self.corridor_ids[edge + 1]]
            segment = next(
                i
                for i in range(len(positions) - 1)
                if min(positions[i], positions[i + 1]) <= edge
                and edge + 1 <= max(positions[i], positions[i + 1])
            )
            start_km, end_km = kms[segment], kms[segment + 1]
            slots.append(
                (
                    edge,
                    forward,
                    segment,
                    (low - start_km) / (end_km - start_km),
                    (high - start_km) / (end_km - start_km),
                )
            )
        return slots

    def pairs(
        self,
        schedules: Mapping[str, Mapping[str, Sequence[float]]],
        service_ids: Sequence[str],
    ) -> Iterator[Tuple[int, int]]:
        """Yield conflicting service pairs as global matrix row tuples.

        Args:
            schedules: Absolute schedule per service and station, as
                ``[arrival, departure]`` in minutes.
            service_ids: Services to consider (e.g. the planned ones).
        """
        groups: Dict[Tuple[int, bool], List[Tuple[int, float, float]]] = defaultdict(
            list
        )
        for sid in service_ids:
            schedule = schedules[sid]
            route = self._route_ids[sid]
            for edge, forward, segment, low_frac, high_frac in self._slots[sid]:
                departure = schedule[route[segment]][1]
                arrival = schedule[route[segment + 1]][0]
                leg = arrival - departure
                low = departure + leg * low_frac
                high = departure + leg * high_frac
                start, end = (low, high) if forward else (high, low)
                groups[(edge, forward)].append((self.row_of[sid], start, end))

        gap = 2 * self.headway
        for group in groups.values():
            if len(group) < 2:
                continue
            rows = np.array([entry[0] for entry in group])
            starts = np.array([entry[1] for entry in group])
            ends = np.array([entry[2] for entry in group])
            d_start = starts[:, None] - starts[None, :]
            d_end = ends[:, None] - ends[None, :]
            clash = (
                (d_start * d_end <= 0)
                | (np.abs(d_start) <= gap)
                | (np.abs(d_end) <= gap)
            )
            lower = np.triu(clash, 1)
            for a, b in zip(*np.nonzero(lower)):
                yield int(rows[a]), int(rows[b])


class GATimetabling:
    """Revenue-maximization problem for the direct genetic encoding.

    The problem exposes the genome layout (block slices and bounds per gene),
    decodes genomes into conflict-free-by-construction ``Solution`` objects
    and evaluates them as the revenue of the scheduled services minus a
    penalty for every conflict between planned services.
    """

    def __init__(
        self,
        supply: Supply,
        revenue_behavior: Mapping[str, Mapping[str, float]],
        safe_headway: int = 10,
        max_stop_time: int = 10,
        im_mod_margin: int = 60,
        conflict_penalty: float = 2.0,
    ) -> None:
        """Build the problem from a supply and its revenue behavior.

        Args:
            supply: Requested services (e.g. from ``data/synthetic/timetable.yaml``).
            revenue_behavior: Revenue parameters per service (e.g. the
                ``services`` section of ``data/synthetic/revenue.yaml``).
            safe_headway: Safety headway between services, in minutes.
            max_stop_time: Maximum dwell-time extension, in minutes.
            im_mod_margin: Departure-time modification margin of the IM, in
                minutes.
            conflict_penalty: Weight ``lambda`` of the conflict penalty. The
                default (2) makes every conflict cost strictly more than
                keeping only the more profitable of the two services, so the
                search is always rewarded for resolving conflicts.
        """
        self.services = list(supply.services)
        self.service_ids = [service.id for service in self.services]
        self.row_index = {sid: i for i, sid in enumerate(self.service_ids)}
        self.revenue_behavior = revenue_behavior
        schedules = get_schedule_from_supply(supply=supply)
        self.reference_schedules = {
            sid: dict(stops) for sid, stops in schedules.items()
        }
        self.requested_schedules = deepcopy(self.reference_schedules)
        self.safe_headway = safe_headway
        self.max_stop_time = max_stop_time
        self.im_mod_margin = im_mod_margin
        self.conflict_penalty = conflict_penalty
        self.n_services = len(self.services)

        self.schedule_manager = ScheduleManager(self.reference_schedules, {})
        self.schedule_manager.operational_times = (
            self.schedule_manager.compute_operational_times()
        )
        self.revenue_calculator = RevenueCalculator(
            revenue_behavior,
            self.reference_schedules,
            dict(self.schedule_manager.updated_schedule),
            im_mod_margin,
        )

        self._build_genome_layout()
        self.conflict_checkers = self._build_conflict_checkers()

    def _origin_delta_upper(self, n_times: int) -> int:
        """Upper bound for the origin delta of a service.

        Every intermediate departure must be at least as late as the origin
        shift but no later than the dwell cap, so services with intermediate
        stops cannot delay their origin beyond ``max_stop_time``. Direct
        services have no intermediate stop and use the full IM margin.
        """
        if n_times == 1:
            return self.im_mod_margin
        return min(self.im_mod_margin, self.max_stop_time)

    def _build_genome_layout(self) -> None:
        """Compute block slices, bounds, dwells and reference departures."""
        self.slices: List[slice] = []
        self.time_slices: List[slice] = []
        self.real_slices: List[slice] = []
        self.dwells: List[np.ndarray] = []

        lower: List[int] = []
        upper: List[int] = []
        departures: List[int] = []
        offset = 0
        real_offset = 0
        for service in self.services:
            schedule = self.reference_schedules[service.id]
            stops = list(schedule)
            n_times = len(stops) - 1
            self.slices.append(slice(offset, offset + n_times + 1))
            self.time_slices.append(slice(offset + 1, offset + n_times + 1))
            self.real_slices.append(slice(real_offset, real_offset + n_times))
            self.dwells.append(
                np.array(
                    [
                        schedule[stops[j]][1] - schedule[stops[j]][0]
                        for j in range(1, n_times)
                    ],
                    dtype=np.int64,
                )
            )
            departures.extend(schedule[stop][1] for stop in stops[:-1])

            lower.extend([0, -self.im_mod_margin])
            upper.extend([1, self._origin_delta_upper(n_times)])
            lower.extend([0] * (n_times - 1))
            upper.extend([self.max_stop_time] * (n_times - 1))
            offset += n_times + 1
            real_offset += n_times

        self.genome_size = offset
        self.lower_bounds = np.array(lower, dtype=np.int64)
        self.upper_bounds = np.array(upper, dtype=np.int64)
        self.reference_departures = np.array(departures, dtype=np.int64)

    def _build_conflict_checkers(self) -> List[CorridorConflicts]:
        """Build one conflict model per corridor of the supply."""
        corridor_routes: Dict[str, Dict[str, List[Station]]] = defaultdict(dict)
        corridor_stations: Dict[str, List[Station]] = {}
        for service in self.services:
            corridor = service.line.corridor
            if corridor.id not in corridor_stations:
                corridor_stations[corridor.id] = self._flatten_corridor(corridor.tree)
            corridor_routes[corridor.id][service.id] = list(service.line.stations)

        return [
            CorridorConflicts(
                corridor=corridor_stations[cid],
                routes=corridor_routes[cid],
                row_of={sid: self.row_index[sid] for sid in corridor_routes[cid]},
                safe_headway=self.safe_headway,
            )
            for cid, stations in corridor_stations.items()
        ]

    @staticmethod
    def _flatten_corridor(tree: Mapping[Station, Mapping]) -> List[Station]:
        """Flatten a corridor tree into its stations in order."""
        stations: List[Station] = []
        for station, subtree in tree.items():
            stations.append(station)
            stations.extend(GATimetabling._flatten_corridor(subtree))
        return stations

    def decode(self, genome: Genome) -> Solution:
        """Decode a genome into a solution with absolute departure times.

        Genes are clipped to their bounds, deltas accumulate downstream
        through :func:`cumulative_shifts` and services with ``b = 0`` keep
        their requested timetable. The resulting schedule is feasible by
        construction; only inter-service conflicts may remain.

        Args:
            genome: Flat integer genome.

        Returns:
            A ``Solution`` with the flat departure times as real part and the
            scheduled mask as discrete part.
        """
        genes = np.clip(
            np.asarray(genome, dtype=np.int64), self.lower_bounds, self.upper_bounds
        )
        real = self.reference_departures.copy()
        discrete = np.zeros(self.n_services, dtype=bool)
        for i in range(self.n_services):
            if not genes[self.slices[i].start]:
                continue
            shifts = cumulative_shifts(
                genes[self.time_slices[i]],
                self.dwells[i],
                self.im_mod_margin,
                self.max_stop_time,
            )
            real[self.real_slices[i]] += shifts
            discrete[i] = True
        return Solution(real=real, discrete=discrete)

    def conflict_matrix(
        self,
        schedules: Mapping[str, Mapping[str, Sequence[float]]],
        service_ids: Optional[Sequence[str]] = None,
    ) -> np.ndarray:
        """Pairwise conflict matrix over the given schedules.

        Args:
            schedules: Absolute schedule per service and station, as
                ``[arrival, departure]`` in minutes.
            service_ids: Services to check; all by default.

        Returns:
            Symmetric boolean matrix with rows and columns in
            ``self.service_ids`` order.
        """
        active = self.service_ids if service_ids is None else list(service_ids)
        matrix = np.zeros((self.n_services, self.n_services), dtype=bool)
        for checker in self.conflict_checkers:
            for a, b in checker.pairs(schedules, active):
                matrix[a, b] = True
                matrix[b, a] = True
        return matrix

    def _planned_conflicts(self, solution: Solution) -> Tuple[List[str], np.ndarray]:
        """Apply a decoded solution and price it.

        Args:
            solution: Decoded solution.

        Returns:
            The planned service ids and their pairwise conflict matrix.
        """
        self.schedule_manager.update_from_solution(solution.real)
        self.revenue_calculator.updated_schedule = dict(
            self.schedule_manager.updated_schedule
        )
        self.revenue_calculator.recompute_all_revenues()
        planned = [
            sid for i, sid in enumerate(self.service_ids) if solution.discrete[i]
        ]
        matrix = self.conflict_matrix(
            dict(self.schedule_manager.updated_schedule), planned
        )
        return planned, matrix

    def fitness(self, genome: Genome) -> float:
        """Evaluate a genome as the penalized revenue of its schedule.

        The schedule is decoded, applied to the schedule manager and priced
        with the revenue calculator; every conflict between planned services
        penalizes the fitness with ``conflict_penalty`` times the revenue of
        its cheaper service.

        Args:
            genome: Flat integer genome.

        Returns:
            Penalized revenue (0.0 when no service is scheduled).
        """
        planned, matrix = self._planned_conflicts(self.decode(genome))
        if not planned:
            return 0.0
        revenues = {
            sid: self.revenue_calculator.get_service_revenue(sid) for sid in planned
        }
        penalty = sum(
            min(revenues[planned[a]], revenues[planned[b]])
            for a in range(len(planned))
            for b in range(a + 1, len(planned))
            if matrix[self.row_index[planned[a]], self.row_index[planned[b]]]
        )
        return float(sum(revenues.values()) - self.conflict_penalty * penalty)

    def decoded_schedule(self, genome: Genome) -> Dict[str, Dict[str, List[float]]]:
        """Complete decoded timetable of a genome.

        Args:
            genome: Flat integer genome.

        Returns:
            Absolute ``[arrival, departure]`` in minutes per service and
            station.
        """
        self.schedule_manager.update_from_solution(self.decode(genome).real)
        return {
            sid: {station: list(times) for station, times in schedule.items()}
            for sid, schedule in self.schedule_manager.updated_schedule.items()
        }

    def describe_genome(self, genome: Genome) -> pd.DataFrame:
        """Per-service view of a genome: planning bit and time deltas.

        Args:
            genome: Flat integer genome.

        Returns:
            One row per service with its RU, stop count, planning bit and
            delta list.
        """
        genes = np.clip(
            np.asarray(genome, dtype=np.int64), self.lower_bounds, self.upper_bounds
        )
        return pd.DataFrame(
            [
                {
                    "service": sid,
                    "ru": self.revenue_behavior[sid]["ru"],
                    "stops": len(self.reference_schedules[sid]),
                    "planned": int(genes[self.slices[i].start]),
                    "deltas": genes[self.time_slices[i]].tolist(),
                }
                for i, sid in enumerate(self.service_ids)
            ]
        )

    def schedule_frame(self, solution: Solution) -> pd.DataFrame:
        """Planned services of a solution with departures and revenue.

        Args:
            solution: Decoded solution.

        Returns:
            One row per planned service with requested/final origin
            departure, the origin delta, its revenue and its canon.
        """
        self.schedule_manager.update_from_solution(solution.real)
        self.revenue_calculator.updated_schedule = dict(
            self.schedule_manager.updated_schedule
        )
        self.revenue_calculator.recompute_all_revenues()

        rows = []
        for i, sid in enumerate(self.service_ids):
            if not solution.discrete[i]:
                continue
            schedule = self.requested_schedules[sid]
            origin = list(schedule)[0]
            final_origin = solution.real[self.real_slices[i]][0]
            rows.append(
                {
                    "service": sid,
                    "ru": self.revenue_behavior[sid]["ru"],
                    "requested_departure": int(schedule[origin][1]),
                    "final_departure": int(final_origin),
                    "origin_delta": int(final_origin - schedule[origin][1]),
                    "revenue": self.revenue_calculator.get_service_revenue(sid),
                    "canon": self.revenue_behavior[sid]["canon"],
                }
            )
        return pd.DataFrame(rows)

    def greedy_baseline(self) -> Tuple[List[str], float]:
        """Revenue of the published heuristic at the requested timetables.

        Iteratively drops the cheapest service of every conflicting pair of
        the requested schedules; with no deviation the revenue of a service
        is its canon.

        Returns:
            The kept service ids and their total revenue.
        """
        canon = {sid: params["canon"] for sid, params in self.revenue_behavior.items()}
        kept = list(self.service_ids)
        matrix = self.conflict_matrix(self.requested_schedules)
        while True:
            positions = [self.row_index[sid] for sid in kept]
            sub = matrix[np.ix_(positions, positions)]
            if not sub.any():
                break
            a, b = next(zip(*np.nonzero(np.triu(sub, 1))))
            first, second = kept[a], kept[b]
            kept.remove(first if canon[first] < canon[second] else second)
        return kept, sum(canon[sid] for sid in kept)

    def conflicting_pairs(self, genome: Genome) -> List[Tuple[str, str]]:
        """Report the conflicts between the planned services of a genome.

        Args:
            genome: Flat integer genome.

        Returns:
            Sorted pairs of service ids in conflict after decoding.
        """
        planned, matrix = self._planned_conflicts(self.decode(genome))
        return sorted(
            (planned[a], planned[b])
            for a in range(len(planned))
            for b in range(a + 1, len(planned))
            if matrix[self.row_index[planned[a]], self.row_index[planned[b]]]
        )
